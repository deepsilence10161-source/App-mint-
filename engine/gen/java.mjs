/**
 * JAVA SOURCE TEMPLATES
 * =====================
 * Generated Android sources. Two things here matter more than the rest:
 *
 * 1. SchemeRouter — the SAFE rewrite of the deep-link/scheme handling found in
 *    the existing ff-user-panel app. That code called
 *    `Intent.parseUri(url, URI_INTENT_SCHEME)` on web-supplied `intent://` URLs
 *    and launched the result without validation — an intent-redirection hole
 *    that lets page content launch arbitrary exported components.
 *
 *    The fix is structural, not a blocklist: we NEVER parse an Intent out of a
 *    URL. We build the Intent ourselves from an allowlisted scheme, so there is
 *    no component, no package, no extras and no grant flags for an attacker to
 *    smuggle. Then we verify something can actually handle it before starting.
 *
 * 2. The JavaScript bridge is OFF by default. `addJavascriptInterface` turns any
 *    XSS in the loaded site into native code execution, so it is generated only
 *    when the project explicitly enables it, and every exposed method validates
 *    its input and runs work off the JS thread.
 */

const pkgPath = (pkg) => pkg.replace(/\./g, '/');

